def main():
    with open(EXISTING_COMBINED, "r", encoding="utf-8") as f:
        existing = json.load(f)
    existing_names = set(d["name"] for d in existing)

    # 既存 phase2_controls も重複対象
    prev = []
    if os.path.exists(OUTPUT_CONTROLS):
        with open(OUTPUT_CONTROLS, "r", encoding="utf-8") as f:
            prev = json.load(f)
    prev_names = set(d["name"] for d in prev)
    skip = existing_names | prev_names

    new_controls = []
    found = 0
    older = 0
    for name in CONTROL_NAMES:
        if name in skip:
            continue
        try:
            text = get_page_text(name)
            if not text:
                print(f"  [SKIP] {name}: ページなし")
                time.sleep(REQUEST_INTERVAL)
                continue
            if has_illness_mention(text):
                print(f"  [SKIP] {name}: 病気記述あり")
                time.sleep(REQUEST_INTERVAL)
                continue
            birth_date = extract_birth_date(text)
            gender = extract_gender(text)
            if not (birth_date and gender):
                print(f"  [SKIP] {name}: 生年月日/性別不明")
                time.sleep(REQUEST_INTERVAL)
                continue
            real_name = extract_real_name(text) or name
            last_name, first_name = split_japanese_name(real_name)
            new_controls.append({
                "name": name,
                "real_name": real_name,
                "last_name": last_name,
                "first_name": first_name,
                "birth_date": birth_date,
                "gender": gender,
                "illness": None,
                "illness_category": None,
                "onset_year": None,
                "notes": "対照群（病気公表なし）",
                "source": "Wikipedia",
                "group": "control",
            })
            found += 1
            if int(birth_date[:4]) <= 1976:
                older += 1
            print(f"  [CTRL] {name}: {birth_date} {gender}")
        except Exception as e:
            print(f"  [ERR] {name}: {e}")
        time.sleep(REQUEST_INTERVAL)

    merged = prev + new_controls
    with open(OUTPUT_CONTROLS, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False, indent=2)
    print(f"\n補助対照収集: {found}名（50歳以上: {older}名） / 累計phase2対照: {len(merged)}名")


if __name__ == "__main__":
    main()
